#!/usr/bin/env node
/**
 * Generates docs/TEST_REPORT.md from ACTUAL runs: typecheck, lint, unit/integration tests (vitest
 * JSON reporter) and, if a server is reachable, the live MCP smoke test. Nothing is hand-written.
 *
 *   node scripts/generate-test-report.mjs           # smoke uses the rule planner
 *   SMOKE_PLANNER=ollama node scripts/generate-test-report.mjs
 */
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import os from "node:os";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const reports = join(root, "reports");
mkdirSync(reports, { recursive: true });
const isWin = process.platform === "win32";

function run(cmd, args, opts = {}) {
  const started = Date.now();
  const r = spawnSync(cmd, args, { cwd: root, encoding: "utf8", shell: isWin, env: { ...process.env, FORCE_COLOR: "0", NO_COLOR: "1" }, ...opts });
  // eslint-disable-next-line no-control-regex
  const strip = (s) => (s ?? "").replace(/\u001b\[[0-9;]*m/g, "");
  return { code: r.status ?? 1, out: strip(r.stdout) + strip(r.stderr), ms: Date.now() - started };
}

const steps = [];
console.log("• typecheck");
steps.push({ name: "Type check (tsc --noEmit, server + web)", ...run("npm", ["run", "typecheck"]) });
console.log("• lint");
steps.push({ name: "Lint (eslint)", ...run("npm", ["run", "lint"]) });
console.log("• server tests");
const serverRun = run("npm", ["run", "test:json", "-w", "server"]);
console.log("• web tests");
const webRun = run("npm", ["run", "test:json", "-w", "web"]);

function readVitest(file, label, runResult) {
  if (!existsSync(file)) return { label, ok: false, total: 0, passed: 0, failed: 0, files: [], error: runResult.out.slice(-1500) };
  const j = JSON.parse(readFileSync(file, "utf8"));
  const files = j.testResults.map((f) => ({
    file: f.name.replace(/\\/g, "/").replace(/^.*?\/(server|web)\//, "$1/"),
    tests: f.assertionResults.map((a) => ({ name: a.fullName ?? a.title, status: a.status, ms: Math.round(a.duration ?? 0) })),
  }));
  return { label, ok: j.success, total: j.numTotalTests, passed: j.numPassedTests, failed: j.numFailedTests, files };
}
const suites = [readVitest(join(reports, "server-tests.json"), "Server", serverRun), readVitest(join(reports, "web-tests.json"), "Web", webRun)];

let smoke = { status: "skipped", out: "" };
const base = process.env.SENTRYFLOW_URL ?? "http://127.0.0.1:8787";
try {
  const h = await fetch(`${base}/health`, { signal: AbortSignal.timeout(2000) });
  if (h.ok) {
    console.log("• live MCP smoke test");
    const r = run("npm", ["run", "smoke"], { timeout: 180000 });
    smoke = { status: r.code === 0 ? "passed" : "failed", out: r.out.trim(), ms: r.ms };
  } else smoke.out = `Server at ${base} answered /health with HTTP ${h.status}.`;
} catch {
  smoke.out = `No server reachable at ${base}; start it with \`npm start\` and re-run \`npm run report\` to include the live MCP test.`;
}

const health = await fetch(`${base}/health`).then((r) => r.json()).catch(() => null);
const now = new Date();
const total = suites.reduce((a, s) => a + s.total, 0);
const passed = suites.reduce((a, s) => a + s.passed, 0);
const failed = suites.reduce((a, s) => a + s.failed, 0);
const icon = (ok) => (ok ? "✅" : "❌");

const md = [];
md.push("# Test Report", "");
md.push(`> Generated by \`npm run report\` (scripts/generate-test-report.mjs) on ${now.toISOString()}. Every number below comes from the runs executed by that script; re-run it to reproduce.`, "");
md.push("## Environment", "");
md.push(`| | |`, `|---|---|`);
md.push(`| OS | ${os.type()} ${os.release()} (${os.arch()}) |`);
md.push(`| CPU | ${os.cpus()[0]?.model ?? "?"} × ${os.cpus().length} |`);
md.push(`| Memory | ${(os.totalmem() / 2 ** 30).toFixed(1)} GiB |`);
md.push(`| Node | ${process.version} |`);
if (health) {
  md.push(`| MCP protocol (server) | ${health.mcp.protocolVersion} over ${health.mcp.transport} |`);
  md.push(`| Planner | configured \`${health.planner.configured}\`, effective \`${health.planner.effective}\`, model \`${health.planner.model}\` |`);
  md.push(`| Policy | ${health.policy.version} |`);
}
md.push("");
md.push("## Summary", "");
md.push("| Check | Result | Time |", "|---|---|---|");
for (const s of steps) md.push(`| ${s.name} | ${icon(s.code === 0)} ${s.code === 0 ? "pass" : `fail (exit ${s.code})`} | ${(s.ms / 1000).toFixed(1)} s |`);
for (const s of suites) md.push(`| ${s.label} tests (vitest) | ${icon(s.ok)} ${s.passed}/${s.total} passed${s.failed ? `, ${s.failed} failed` : ""} | |`);
md.push(`| Live MCP smoke test (${process.env.SMOKE_PLANNER ?? "rules"} planner) | ${smoke.status === "passed" ? "✅ pass" : smoke.status === "failed" ? "❌ fail" : "⏭️ skipped"} | ${smoke.ms ? (smoke.ms / 1000).toFixed(1) + " s" : ""} |`);
md.push("", `**Total automated tests: ${passed}/${total} passed${failed ? `, ${failed} failed` : ""}.**`, "");
for (const s of steps.filter((x) => x.code !== 0)) md.push(`### ${s.name} output`, "", "```", s.out.slice(-3000), "```", "");

for (const s of suites) {
  md.push(`## ${s.label} test cases`, "");
  if (s.error) md.push("```", s.error, "```", "");
  for (const f of s.files) {
    md.push(`### \`${f.file}\``, "");
    for (const t of f.tests) md.push(`- ${t.status === "passed" ? "✅" : t.status === "failed" ? "❌" : "⏭️"} ${t.name}`);
    md.push("");
  }
}

md.push("## Live MCP smoke test", "");
md.push("Runs `server/scripts/mcp-smoke.ts`: the official MCP SDK client against the running server over Streamable HTTP (initialize → tools/list → tools/call).", "");
md.push("```", smoke.out || "(no output)", "```", "");
md.push("## What these tests do not prove", "");
md.push("- Passing tests do not make the system secure; they check the specific properties listed above.");
md.push("- Model-planner behaviour is non-deterministic; the unit tests use stubbed model output, and the live run reflects one sample.");
md.push("- No real devices, no Alexa+ cloud integration, and no OAuth flow are exercised (see docs/ASSUMPTIONS.md).");
md.push("");

writeFileSync(join(root, "docs", "TEST_REPORT.md"), md.join("\n"));
console.log(`\nWrote docs/TEST_REPORT.md — ${passed}/${total} tests passed; smoke ${smoke.status}.`);
process.exit(steps.every((s) => s.code === 0) && suites.every((s) => s.ok) && smoke.status !== "failed" ? 0 : 1);
